export function ruleLines(rules: string[]): string {
  return rules.map((r) => `- ${r}`).join("\n");
}

/** 稿型是不是口播 / 短视频（只有这类注入口播流畅与开头诊断，长文不带，省 prompt 预算） */
export function isSpokenTrackPack(trackPackId: string | undefined): boolean {
  return trackPackId === KOUBO_PACK.id;
}

/**
 * 「核心被稀释」兜底：深度判据（有调研）或角度判据（有角度卡）在场时，它们已经在问同一件事，
 * 再挂一条只会让同一处毛病被判两遍、白烧一轮修订。
 */
export function coreClaimSection(present: boolean): string[] {
  if (!present) return [];
  return [
    "",
    "## 判据：核心主张（本稿没有调研材料也没有角度卡，由这一条兜底）",
    "- 核心被稀释（blocker）：几个主张平铺并列，读完说不出这篇到底要讲的那一句话；" +
      "其余内容应当是在给这句话提供证据、例子、解释或行动建议。创作者明确要求的清单式结构不因此打回。",
  ];
}

